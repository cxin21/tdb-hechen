/**
 * 召回日志分析修复（2026-10-14，用户拍板「全部修复并推git」）：
 * sanitizeText 增补 DSH harness 噪音剥离——acp 代理标记、系统注入块、回合脚手架行。
 *
 * 背景（journal 实测，b67）：查询文本携带 `<acp tokens="…" type="…">mNNNNN</acp>` 与
 * Time sampled / Elapsed / Browser time zone 脚手架行，直接进 FTS/embedding 造成查询侧
 * 污染。sanitizeText 为 capture（L0 录制）与 recall（查询清洗）共用 → 双侧同剥：
 * 新噪音不再入语料，查询侧归位纯用户意图（宁缺毋滥）。
 */
import { describe, expect, it } from "vitest";
import { sanitizeText } from "../sanitize.js";

describe("sanitizeText · DSH harness 噪音剥离", () => {
  it("剥 <acp …>mNNNNN</acp> 标记（保留正文）", () => {
    const raw = '<acp tokens="18" type="text">m02894</acp>\n检查一下现在的召回逻辑';
    expect(sanitizeText(raw)).toBe("检查一下现在的召回逻辑");
  });

  it("剥 system-reminder / current_feeling 系统注入块（整块含内容）", () => {
    const raw = [
      "<system-reminder>",
      "The available skill catalog changed. This complete catalog replaces every earlier list.",
      "</system-reminder>",
      "真实问题正文",
      "<current_feeling>",
      "数据完整优先。",
      "</current_feeling>",
    ].join("\n");
    expect(sanitizeText(raw)).toBe("真实问题正文");
  });

  it("剥回合脚手架行（Time sampled / Browser time zone / Elapsed）", () => {
    const raw = [
      "Time sampled while preparing turn 45, step 1: 2026-10-14T15:42:53+08:00[Asia/Shanghai]",
      "Browser time zone for this request: Asia/Shanghai. Interpret otherwise-unqualified dates and times in this zone.",
      "Elapsed since the preceding model-visible message: 3h 23m 39s.",
      "帮我修复这个 bug",
    ].join("\n");
    expect(sanitizeText(raw)).toBe("帮我修复这个 bug");
  });

  it("剥 [model changed: …] 标记行（含 provider 斜杠）", () => {
    const raw =
      "[model changed: assistant turns above this point were generated by tdb/scm-flash]\n继续修复";
    expect(sanitizeText(raw)).toBe("继续修复");
  });

  it("纯噪音输入 → 空串（searchMemories 长度守卫接手，触发零搜索）", () => {
    const raw =
      '<acp tokens="1" type="text">m1</acp>\nTime sampled while preparing turn 46, step 1: 2026-10-14T17:02:37+08:00[Asia/Shanghai]';
    expect(sanitizeText(raw)).toBe("");
  });

  it("脚手架变体：Elapsed since the preceding step context（m03163 实证措辞）也整行剥离", () => {
    const raw = [
      '<acp tokens="63" type="text">m03163</acp>',
      "Time sampled while preparing turn 48, step 34: 2026-10-14T17:33:24+08:00[Asia/Shanghai]",
      "Browser time zone for this request: Asia/Shanghai. Interpret otherwise-unqualified dates and times in this zone.",
      "Elapsed since the preceding step context: 10m 5s.",
    ].join("\n");
    expect(sanitizeText(raw)).toBe("");
  });

  it("效率 nudge 整体剥离（正文英文散文残句曾以弱相关注入记忆）", () => {
    const raw = [
      "This is an efficiency nudge to compress early and keep context lean — not an overflow warning.",
      "Context breakdown: 24.9K tool | 12.3K summaries | 41.5K text",
      "HOW TO COMPRESS",
      "- Work from summaries, not raw tool outputs.",
    ].join("\n");
    expect(sanitizeText(raw)).toBe("");
  });

  it("普通用户文本逐位保留（不误伤正文）", () => {
    const raw = "重启 tdai-core 后 journal 行为不变，rerank gate 仍在；importancePenalty=0.3";
    expect(sanitizeText(raw)).toBe(raw);
  });

  // ── #74 Batch A（合同 docs/research/2026-10-20-recall-batch-a-contract.md §1.1）：
  // 六 pattern 补全——裸 m\d{5} ref、⚠️/Context limit 行、【Compressed…】区段头、方括号 POV 标签头 ──

  it("剥裸 mNNNNN ref token（#74 D4-1：词边界删 token 留正文）", () => {
    const raw = "这条引用了早前消息 m00207 与 m00311 的上下文";
    expect(sanitizeText(raw)).toBe("这条引用了早前消息  与  的上下文");
  });

  it("m-ref 不误伤：无 m+5 位数形态的普通文本逐位保留", () => {
    const raw = "编号 team-2k12 与版本 v1.0 的 m2501.13956 论文号保留";
    expect(sanitizeText(raw)).toBe(raw);
  });

  it("剥 ⚠️/Context limit 系统提醒行（#74 D4-2：整行删，T4 §3 字面撞车实锤）", () => {
    const raw = "⚠️ Context limit reached — compress now\n真实问题：召回精度怎么提";
    expect(sanitizeText(raw)).toBe("真实问题：召回精度怎么提");
  });

  it("剥【Compressed conversation section】区段头（#74 D4-3：整行删，区段正文保留交两级策略）", () => {
    const raw = "【Compressed conversation section】— 任务接单与团队组建\n压缩区段里的真实查询内容";
    expect(sanitizeText(raw)).toBe("压缩区段里的真实查询内容");
  });

  it("剥 [Compressed conversation section] 半角形态区段头（审查 M1：生产 journal 唯一实际形态，与全角整行删行为对齐）", () => {
    const raw = "[Compressed conversation section] — 任务接单与团队组建\n压缩区段里的真实查询内容";
    expect(sanitizeText(raw)).toBe("压缩区段里的真实查询内容");
  });

  it("剥 [current_feeling]/[soul-*] 方括号标签头（#74 D4-4：删 token 留正文，含属性形式）", () => {
    const raw = '[current_feeling] 用户拍板优先\n[soul-event kind="redline"] 红线内容\n正文结论';
    expect(sanitizeText(raw)).toBe("用户拍板优先\n红线内容\n正文结论");
  });
});
